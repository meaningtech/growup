export const dictionaries: Record<Locale, Dictionary> = { en, it };
const I18nContext = createContext<{ locale: Locale; setLocale: (locale: Locale) => void; t: (key: string, values?: Record<string, string | number>) => string } | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => {
    const stored = localStorage.getItem('growup.locale');
    if (stored === 'en' || stored === 'it') return stored;
    return navigator.language.toLowerCase().startsWith('it') ? 'it' : 'en';
  });
  useEffect(() => {
    localStorage.setItem('growup.locale', locale);
    document.documentElement.lang = locale;
  }, [locale]);
  const value = useMemo(() => ({
    locale,
    setLocale,
    t: (key: string, values: Record<string, string | number> = {}) => {
      const template = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
      return Object.entries(values).reduce((result, [name, replacement]) => result.replaceAll(`{${name}}`, String(replacement)), template);
    },
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}
